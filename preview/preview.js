const builds = [
  ["START_HERE.cmd windows", "../docs/BUILD_WINDOWS.md"],
  ["START_HERE.cmd android-original", "../docs/BUILD_ANDROID_ORIGINAL.md"],
  ["build_android_full.cmd", "../docs/BUILD_ANDROID_FULL.md"]
];
const menu = document.getElementById("language");

function element(tag, text, className) {
  const node = document.createElement(tag);
  node.textContent = text;
  if (className) node.className = className;
  return node;
}

function render(language) {
  const lang = Object.hasOwn(messages, language) ? language : "en";
  const t = messages[lang];
  document.documentElement.lang = lang;
  document.title = t.title;
  menu.value = lang;
  document.querySelectorAll("[data-text]").forEach(node => {
    node.textContent = t[node.dataset.text];
  });
  document.getElementById("source-image").alt = t.alt;
  document.getElementById("steps").replaceChildren(...t.steps.map(step => element("li", step)));
  const cards = t.cards.map(([title, status, inputs], i) => {
    const [command, href] = builds[i];
    const card = document.createElement("article");
    card.className = "card";
    const guide = element("a", t.guide, "reference");
    guide.href = href;
    guide.hreflang = "en";
    card.append(element("h3", title), element("p", status, "state"),
                element("p", inputs, "inputs"), element("code", command, "command"), guide);
    return card;
  });
  document.getElementById("cards").replaceChildren(...cards);
}

function selected() {
  const supplied = new URLSearchParams(location.search).get("lang");
  if (supplied) return supplied;
  try {
    return localStorage.getItem("blinx-toolkit-preview-language") || "en";
  } catch {
    return "en";
  }
}

menu.addEventListener("change", () => {
  const lang = menu.value;
  try {
    localStorage.setItem("blinx-toolkit-preview-language", lang);
  } catch {
    // Local-file viewers may disable storage. The menu still works in this session.
  }
  const url = new URL(location.href);
  url.searchParams.set("lang", lang);
  try {
    history.replaceState(null, "", url);
  } catch {
    // Some local-file viewers prohibit URL changes.
  }
  render(lang);
});
render(selected());
